import { GoogleGenAI, ThinkingLevel } from "@google/genai";
import {
  GEMMA_MODEL_DEFAULT,
  GEMMA_MODELS,
  GEMMA_SYSTEM_INSTRUCTION,
  buildGemmaPrompt,
  demoInsights,
  parseModelInsight,
  validateSnapshot,
  type GemmaModelId,
} from "@/lib/analysis";

function isGemmaModel(value: string): value is GemmaModelId {
  return GEMMA_MODELS.includes(value as GemmaModelId);
}

export async function POST(request: Request) {
  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return Response.json({ ok: false, error: "Send the aggregated ledger as JSON." }, { status: 400 });
  }

  const snapshot = validateSnapshot(body);
  if (!snapshot) {
    return Response.json({ ok: false, error: "The analysis request did not include ledger totals." }, { status: 400 });
  }

  const requested = process.env.GEMMA_MODEL?.trim();
  if (requested && !isGemmaModel(requested)) {
    return Response.json(
      { ok: false, error: `GEMMA_MODEL must be one of: ${GEMMA_MODELS.join(", ")}.` },
      { status: 500 },
    );
  }

  const model: GemmaModelId = requested && isGemmaModel(requested) ? requested : GEMMA_MODEL_DEFAULT;
  const apiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY;
  if (!apiKey) {
    return Response.json({
      ok: true,
      source: "demo",
      model: null,
      notice: "No GEMINI_API_KEY is configured on the server. These are demo insights written by the application, not live Gemma 4 output.",
      insight: demoInsights(snapshot),
    });
  }

  try {
    const ai = new GoogleGenAI({ apiKey });
    const response = await Promise.race([
      ai.models.generateContent({
        model,
        contents: buildGemmaPrompt(snapshot),
        config: {
          systemInstruction: GEMMA_SYSTEM_INSTRUCTION,
          temperature: 0.3,
          maxOutputTokens: 1200,
          thinkingConfig: { thinkingLevel: ThinkingLevel.MINIMAL },
        },
      }),
      new Promise<never>((_, reject) => {
        setTimeout(() => reject(new Error("Gemma 4 did not respond within 25 seconds.")), 25_000);
      }),
    ]);
    const text = response.text ?? "";
    const parsed = parseModelInsight(text);
    const insight = parsed ?? {
      summary: text.trim() || "Gemma 4 returned an empty response.",
      trends: "",
      recommendations: [],
      recordkeeping: "",
      reviewNotes: "The model response was not valid JSON. Any text in the summary is the raw reply.",
    };
    return Response.json({
      ok: true,
      source: "gemma-4",
      model,
      notice: "Generated by Gemma 4 from the aggregated figures on this page. This is commentary, not a verified credit assessment.",
      insight,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "The Gemma 4 request failed.";
    return Response.json({ ok: false, error: message }, { status: 502 });
  }
}
